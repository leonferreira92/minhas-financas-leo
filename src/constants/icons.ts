/** Categorias de navegação do seletor (estilo Mobills) */
export type IconCategoryId =
  | "geral"
  | "casa"
  | "alimentacao"
  | "transporte"
  | "saude"
  | "lazer"
  | "financas";

export interface IconCategoryMeta {
  id: IconCategoryId;
  label: string;
}

export const ICON_CATEGORIES: IconCategoryMeta[] = [
  { id: "geral", label: "Geral" },
  { id: "casa", label: "Casa" },
  { id: "alimentacao", label: "Alimentação" },
  { id: "transporte", label: "Transporte" },
  { id: "saude", label: "Saúde" },
  { id: "lazer", label: "Lazer" },
  { id: "financas", label: "Finanças" },
];

export type AppIconComponent = LucideIcon | IconType;

export interface IconDefinition {
  name: string;
  label: string;
  tags: string[];
  category: IconCategoryId;
  component: AppIconComponent;
}

function icon(
  name: string,
  label: string,
  category: IconCategoryId,
  component: AppIconComponent,
  extraTags: string[] = [],
): IconDefinition {
  const tags = Array.from(
    new Set(
      [
        name,
        label,
        ...label.toLowerCase().split(/\s+/),
        name.toLowerCase(),
        ...extraTags.map((t) => t.toLowerCase()),
      ].filter(Boolean),
    ),
  );
  return { name, label, tags, category, component };
}

