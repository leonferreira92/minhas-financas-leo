/** Mapa nome → componente (compatível com o app legado) */
export const ICON_MAP: Record<string, AppIconComponent> = Object.fromEntries(
  ICONS_LIBRARY.map((item) => [item.name, item.component]),
);

/** Metadados indexados por nome */
export const ICON_META_BY_NAME: Record<string, IconDefinition> =
  Object.fromEntries(ICONS_LIBRARY.map((item) => [item.name, item]));

const FALLBACK_ICON = Folder;

/** Resolve ícone por nome; fallback Folder (estilo Mobills) */
export const getIcon = (name: string): AppIconComponent =>
  ICON_MAP[name] || FALLBACK_ICON;

/** Busca por nome, label ou tags (PT/EN) */
export function searchIcons(
  query: string,
  category?: IconCategoryId | "all",
): IconDefinition[] {
  const term = query.trim().toLowerCase();
  return ICONS_LIBRARY.filter((item) => {
    if (category && category !== "all" && item.category !== category) {
      return false;
    }
    if (!term) return true;
    return item.tags.some((t) => t.includes(term));
  });
}

